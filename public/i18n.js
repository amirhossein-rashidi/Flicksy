  var current = "en";

  function dirOf(code) {
    for (var i = 0; i < LANGUAGES.length; i++) if (LANGUAGES[i].code === code) return LANGUAGES[i].dir;
    return "ltr";
  }

  window.I18N = {
    languages: LANGUAGES,
    get lang() { return current; },
    set: function (code) {
      if (!STRINGS[code]) code = "en";
      current = code;
      document.documentElement.lang = code;
      document.documentElement.dir = dirOf(code);
    },
    isRtl: function () { return dirOf(current) === "rtl"; },
    // t("key", { n: 3 }) -> translated text with {n} replaced. Falls back to English, then the key.
    t: function (key, params) {
      var text = (STRINGS[current] && STRINGS[current][key]);
      if (text === undefined) text = STRINGS.en[key];
      if (text === undefined) return key;
      if (params) {
        Object.keys(params).forEach(function (k) {
          text = text.split("{" + k + "}").join(String(params[k]));
        });
      }
      return text;
    }
  };
